foreach $d (@todo) {
  *dev = $d;
  $missing = 0;
  for $m (@dev) {
    next if $m eq "G609"; # Skip core plane interface for now
    next if $m eq "G610"; # Skip core plane interface for now
    $m =~ /^(.)/;
    $dir = "$1" . "xxx";
    unless (-f "$dir/$m/${m}X.brd" || -f "$dir/$m/$m.nox") {
      # warn "$dir/$m/${m}X.brd is missing\n";
      $missing{"$dir/$m/${m}X.brd"} = $d;
      $missing++;
    }
    @images = <$dir/$m/${m}?back.jpg>;
    unless (-f $images[0]) {
      # warn "$dir/$m/${m}*.jpg is missing\n";
      $missing{"$dir/$m/${m}*.jpg"} = $d;
      # $missing++;
    }
  }
  if ($missing) {
      print "$d is missing ", $missing, " module types\n";
  } else {
      print "$d is finished!\n";
  }
}

foreach $m (sort keys %missing) {
  print "$m is missing ($missing{$m})\n";
}
